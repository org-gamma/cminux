// src/emitter.cpp
// Prints a rewritten token stream as a C++ translation unit.

#include "emitter.hpp"
#include <sstream>
#include <cctype>

namespace cmx {

namespace {

bool is_word_char(char c) {
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
           (c >= '0' && c <= '9') || c == '_';
}

bool is_word_token(const Token& t) {
    return t.kind == TokKind::Ident
        || t.kind == TokKind::Keyword
        || t.kind == TokKind::Number;
}

bool needs_space(const Token& prev, const Token& cur) {
    if (prev.kind == TokKind::Newline) return false;

    const std::string& p = prev.text;
    const std::string& c = cur.text;

    if (p == "#include") return true;

    if (c == "," || c == ";" || c == ")" || c == "]" || c == "}") return false;
    if (p == "(" || p == "[" || p == "{") return false;

    if (c == "." || c == "->") return false;
    if (p == "." || p == "->") return false;

    if (c == "::" || p == "::") return false;

    if (is_word_token(prev) && is_word_token(cur)) return true;

    if (is_word_token(prev) && cur.kind == TokKind::String) return true;
    if (prev.kind == TokKind::String && is_word_token(cur)) return true;

    return false;
}

} // namespace

std::string emit_cpp(const std::vector<Token>& tokens,
                     const EmitOptions& opts) {
    std::ostringstream out;

    if (opts.emit_prologue) {
        out << "// generated by cminux v1.0.0 \xe2\x80\x94 do not edit\n";
        out << "// source: " << opts.source_filename << "\n";
        out << "#include \"outfn.hpp\"\n";
        out << "using cmx::print;\n";
        out << "using cmx::println;\n";
        out << "\n";
        if (opts.emit_line_directive) {
            out << "#line 1 \"" << opts.source_filename << "\"\n";
        }
    }

    const Token* prev = nullptr;
    bool at_line_start = true;

    for (size_t i = 0; i < tokens.size(); ++i) {
        const Token& t = tokens[i];

        if (t.kind == TokKind::End) break;

        if (t.kind == TokKind::Newline) {
            out << '\n';
            prev = nullptr;
            at_line_start = true;
            continue;
        }

        if (t.kind == TokKind::Punct && t.text == " ") {
            out << ' ';
            prev = nullptr;
            at_line_start = false;
            continue;
        }

        if (!at_line_start && prev && needs_space(*prev, t)) {
            out << ' ';
        }

        if (t.kind == TokKind::String) {
            out << '"';
            for (char ch : t.text) {
                if (ch == '"' || ch == '\\') out << '\\';
                out << ch;
            }
            out << '"';
        } else {
            out << t.text;
        }

        prev = &t;
        at_line_start = false;
    }

    if (!at_line_start) out << '\n';
    return out.str();
}

} // namespace cmx